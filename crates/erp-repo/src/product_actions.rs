//! Product mutations with an atomic durable receipt. HTTP retries never create
//! a second object, and cell saves compare the observed database revision.
use crate::product_grid::ProductGridRow;
use chrono::{DateTime, Utc};
use erp_grid_core::{
    ColumnId, RowId,
    actions::{ActionCommand, ActionOutcome, ActionReceipt},
};
use erp_types::{TenantId, UserId};
use serde_json::Value;
use sqlx::{PgPool, Postgres, QueryBuilder, Transaction};
use uuid::Uuid;

pub const COPY: &str = "products.copy";
pub const UPDATE: &str = "products.update";
const PRODUCT_COLUMNS: &str =
    "product_id, tenant_id, product_code, name, brand, category, status, created_at, updated_at";

#[derive(Debug, thiserror::Error)]
pub enum ActionError {
    #[error("{0}")]
    Invalid(&'static str),
    #[error("Operation identity was already used for a different command")]
    IdentityConflict,
    #[error("Stored operation receipt failed verification")]
    ReceiptMismatch,
    #[error("Database operation failed")]
    Database(#[from] sqlx::Error),
    #[error("Operation receipt encoding failed")]
    Encoding(#[from] serde_json::Error),
}

pub fn validate(command: &ActionCommand) -> Result<(), ActionError> {
    command.validate().map_err(ActionError::Invalid)?;
    if let Some(version) = &command.expected_version {
        DateTime::parse_from_rfc3339(version)
            .map_err(|_| ActionError::Invalid("Invalid product version"))?;
    }
    match command.action.as_str() {
        COPY if command.values.is_empty() => Ok(()),
        UPDATE
            if command.expected_version.is_some()
                && !command.values.is_empty()
                && command.values.keys().all(|column| column.0 <= 3)
                && command
                    .values
                    .get(&ColumnId(1))
                    .is_none_or(|name| !name.trim().is_empty()) =>
        {
            Ok(())
        }
        COPY => Err(ActionError::Invalid(
            "Copy values are generated by the product adapter",
        )),
        UPDATE => Err(ActionError::Invalid(
            "Update requires a version and editable product columns 0–3",
        )),
        _ => Err(ActionError::Invalid("Unknown product action")),
    }
}

pub async fn receipt(
    pool: &PgPool,
    tenant: TenantId,
    actor: UserId,
    operation: RowId,
) -> Result<Option<ActionReceipt>, ActionError> {
    let row: Option<(Value, Option<Value>)> = sqlx::query_as("select command, receipt from grid_product_operations where tenant_id = $1 and actor_user_id = $2 and operation_id = $3")
        .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(Uuid::from_u128(operation.0)).fetch_optional(pool).await?;
    row.and_then(|(command, receipt)| receipt.map(|receipt| (command, receipt)))
        .map(|(command, receipt)| decode_receipt(command, receipt))
        .transpose()
}

fn decode_receipt(command: Value, mut value: Value) -> Result<ActionReceipt, ActionError> {
    let command: ActionCommand = serde_json::from_value(command)?;
    command
        .validate()
        .map_err(|_| ActionError::ReceiptMismatch)?;
    let fingerprint = command.fingerprint();
    // 0.18 receipts can be enriched only from the immutable command in the same
    // tenant/actor ledger row, never from a caller's candidate payload.
    if let Some(object) = value.as_object_mut() {
        object
            .entry("command_fingerprint")
            .or_insert_with(|| Value::String(fingerprint.clone()));
    }
    let receipt: ActionReceipt = serde_json::from_value(value)?;
    if receipt.operation_id != command.operation_id
        || receipt.source != command.source
        || receipt.command_fingerprint != fingerprint
    {
        return Err(ActionError::ReceiptMismatch);
    }
    Ok(receipt)
}

fn rejected(code: &str, message: &str) -> ActionOutcome {
    ActionOutcome::Rejected {
        code: code.into(),
        message: message.into(),
    }
}
fn applied(row: ProductGridRow) -> ActionOutcome {
    ActionOutcome::Applied {
        row: RowId(row.product_id.as_u128()),
        version: row.updated_at.to_rfc3339(),
        values: [
            (ColumnId(0), row.product_code.unwrap_or_default()),
            (ColumnId(1), row.name),
            (ColumnId(2), row.brand.unwrap_or_default()),
            (ColumnId(3), row.category.unwrap_or_default()),
            (ColumnId(4), row.status),
            (ColumnId(5), row.created_at.to_rfc3339()),
            (ColumnId(6), row.updated_at.to_rfc3339()),
        ]
        .into(),
    }
}

pub async fn execute(
    pool: &PgPool,
    tenant: TenantId,
    actor: UserId,
    command: &ActionCommand,
) -> Result<ActionReceipt, ActionError> {
    validate(command)?;
    let encoded = serde_json::to_value(command)?;
    let operation = Uuid::from_u128(command.operation_id.0);
    let mut tx = pool.begin().await?;
    sqlx::query("set transaction isolation level repeatable read")
        .execute(&mut *tx)
        .await?;
    sqlx::query("set local statement_timeout = '10s'")
        .execute(&mut *tx)
        .await?;
    sqlx::query("set local lock_timeout = '3s'")
        .execute(&mut *tx)
        .await?;
    sqlx::query("insert into grid_product_operations(tenant_id, actor_user_id, operation_id, command) values ($1, $2, $3, $4) on conflict do nothing")
        .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(operation).bind(&encoded).execute(&mut *tx).await?;
    let (stored, previous): (Value, Option<Value>) = sqlx::query_as("select command, receipt from grid_product_operations where tenant_id=$1 and actor_user_id=$2 and operation_id=$3 for update")
        .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(operation).fetch_one(&mut *tx).await?;
    if stored != encoded {
        return Err(ActionError::IdentityConflict);
    }
    if let Some(previous) = previous {
        let previous = decode_receipt(stored, previous)?;
        tx.commit().await?;
        return Ok(previous);
    }
    let source: Option<ProductGridRow> = sqlx::query_as(&format!("select {PRODUCT_COLUMNS} from products where tenant_id=$1 and product_id=$2 and status <> 'DELETED' for update"))
        .bind(Uuid::from(tenant)).bind(Uuid::from_u128(command.source.0)).fetch_optional(&mut *tx).await?;
    let before = source.as_ref().map(serde_json::to_value).transpose()?;
    sqlx::query("savepoint grid_action")
        .execute(&mut *tx)
        .await?;
    let mut copied_skus = None;
    let outcome = match source {
        None => Ok(rejected(
            "NOT_FOUND",
            "Product was removed or is outside this merchant",
        )),
        Some(ref row)
            if command.expected_version.as_ref().is_some_and(|version| {
                DateTime::parse_from_rfc3339(version)
                    .map(|version| version.with_timezone(&Utc) != row.updated_at)
                    .unwrap_or(true)
            }) =>
        {
            Ok(rejected(
                "VERSION_CONFLICT",
                "Product changed; refresh before saving or copying",
            ))
        }
        Some(_) if command.action == UPDATE => update(&mut tx, tenant, command).await,
        Some(_) => copy(&mut tx, tenant, command.source, &mut copied_skus).await,
    };
    let outcome = match outcome {
        Ok(outcome) => outcome,
        Err(ActionError::Database(sqlx::Error::Database(ref error)))
            if error.code().as_deref() == Some("23505") =>
        {
            rejected("DUPLICATE_CODE", "Product code already exists")
        }
        Err(error) => return Err(error),
    };
    if matches!(outcome, ActionOutcome::Rejected { .. }) {
        sqlx::query("rollback to savepoint grid_action")
            .execute(&mut *tx)
            .await?;
    }
    let result = ActionReceipt {
        operation_id: command.operation_id,
        source: command.source,
        command_fingerprint: command.fingerprint(),
        outcome,
    };
    if let ActionOutcome::Applied { row, .. } = &result.outcome {
        let metadata = serde_json::json!({"operation_id": command.operation_id, "source": command.source, "result": result, "copied_skus": copied_skus});
        sqlx::query("insert into operation_logs(tenant_id, actor_type, actor_user_id, action, ref_type, ref_id, metadata) values ($1, 'USER', $2, $3, 'PRODUCT', $4, $5)")
            .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(&command.action).bind(row.to_uuid()).bind(&metadata).execute(&mut *tx).await?;
        sqlx::query("insert into audit_logs(tenant_id, user_id, action, entity_type, entity_id, before_json, after_json) values ($1, $2, $3, 'PRODUCT', $4, $5, $6)")
            .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(&command.action).bind(row.to_uuid()).bind(before).bind(&metadata).execute(&mut *tx).await?;
    }
    sqlx::query("update grid_product_operations set receipt=$4 where tenant_id=$1 and actor_user_id=$2 and operation_id=$3")
        .bind(Uuid::from(tenant)).bind(Uuid::from(actor)).bind(operation).bind(serde_json::to_value(&result)?).execute(&mut *tx).await?;
    tx.commit().await?;
    Ok(result)
}

async fn update(
    tx: &mut Transaction<'_, Postgres>,
    tenant: TenantId,
    command: &ActionCommand,
) -> Result<ActionOutcome, ActionError> {
    let mut qb = QueryBuilder::<Postgres>::new("update products set ");
    for (column, value) in &command.values {
        let name = match column.0 {
            0 => "product_code",
            1 => "name",
            2 => "brand",
            3 => "category",
            _ => return Err(ActionError::Invalid("Unsupported product column")),
        };
        qb.push(name)
            .push(" = ")
            .push_bind(if value.trim().is_empty() {
                None
            } else {
                Some(value.trim().to_owned())
            })
            .push(", ");
    }
    qb.push("updated_at = greatest(clock_timestamp(), updated_at + interval '1 microsecond') where tenant_id = ").push_bind(Uuid::from(tenant));
    qb.push(" and product_id = ")
        .push_bind(Uuid::from_u128(command.source.0));
    qb.push(" returning ").push(PRODUCT_COLUMNS);
    let row = qb.build_query_as().fetch_one(&mut **tx).await?;
    Ok(applied(row))
}

async fn copy(
    tx: &mut Transaction<'_, Postgres>,
    tenant: TenantId,
    source: RowId,
    copied_skus: &mut Option<Value>,
) -> Result<ActionOutcome, ActionError> {
    let tenant = Uuid::from(tenant);
    let source = Uuid::from_u128(source.0);
    let source_skus: Vec<Uuid> = sqlx::query_scalar("select sku_id from skus where tenant_id=$1 and product_id=$2 and status <> 'DELETED' order by sku_id limit 1001 for share")
        .bind(tenant).bind(source).fetch_all(&mut **tx).await?;
    if source_skus.len() > 1000 {
        return Ok(rejected(
            "TOO_MANY_SKUS",
            "Product copy supports at most 1000 SKU variants per product",
        ));
    }
    let bom_count: i64 = sqlx::query_scalar("select count(*) from (select 1 from sku_boms where tenant_id=$1 and bundle_sku_id = any($2) limit 10001) b")
        .bind(tenant).bind(&source_skus).fetch_one(&mut **tx).await?;
    if bom_count > 10000 {
        return Ok(rejected(
            "TOO_MANY_COMPONENTS",
            "Product copy supports at most 10000 BOM entries",
        ));
    }
    let invalid_bom: bool = sqlx::query_scalar("select exists(select 1 from sku_boms b where b.tenant_id=$1 and b.bundle_sku_id = any($2) and (b.qty <= 0 or not exists(select 1 from skus s where s.tenant_id=$1 and s.sku_id=b.component_sku_id and s.status <> 'DELETED')))")
        .bind(tenant).bind(&source_skus).fetch_one(&mut **tx).await?;
    if invalid_bom {
        return Ok(rejected(
            "INVALID_BOM",
            "BOM contains an unavailable component; repair it before copying",
        ));
    }
    let product = Uuid::new_v4();
    let row: ProductGridRow = sqlx::query_as(&format!("insert into products(product_id, tenant_id, product_code, name, alias, brand, category, base_unit, second_unit, primary_barcode, product_tags, remark, warning_stock, batch_enabled, shelf_life_days, forbid_sale_days, serial_enabled, serial_push_platform, attrs, allow_negative_stock, status) select $3, tenant_id, $4, name || ' (Copy)', alias, brand, category, base_unit, second_unit, null, product_tags, remark, '{{}}'::jsonb, batch_enabled, shelf_life_days, forbid_sale_days, serial_enabled, false, attrs, false, 'INACTIVE' from products where tenant_id=$1 and product_id=$2 returning {PRODUCT_COLUMNS}"))
        .bind(tenant).bind(source).bind(product).bind(format!("COPY-{}", product.simple())).fetch_one(&mut **tx).await?;
    let new_skus: Vec<_> = source_skus.iter().map(|_| Uuid::new_v4()).collect();
    sqlx::query("insert into skus(sku_id, tenant_id, product_id, sku_code, barcode, name, note, spec, tags, image_urls, weight_gram, length_mm, width_mm, height_mm, volume_cm3, sku_kind, cost_cent, is_active, status, batch_enabled, serial_enabled) select m.new_id, s.tenant_id, $2, 'COPY-' || replace(m.new_id::text, '-', ''), null, s.name, s.note, s.spec, s.tags, s.image_urls, s.weight_gram, s.length_mm, s.width_mm, s.height_mm, s.volume_cm3, s.sku_kind, null, false, 'INACTIVE', s.batch_enabled, s.serial_enabled from unnest($3::uuid[], $4::uuid[]) m(old_id, new_id) join skus s on s.sku_id=m.old_id and s.tenant_id=$1")
        .bind(tenant).bind(product).bind(&source_skus).bind(&new_skus).execute(&mut **tx).await?;
    // Internal components point at the copied SKU; external catalogue components
    // retain their merchant-scoped identity. Inventory and channel mappings never copy.
    sqlx::query("insert into sku_boms(tenant_id, bundle_sku_id, component_sku_id, qty, bom_version, updated_at, expire_at) select b.tenant_id, m.new_id, coalesce(($3::uuid[])[array_position($2::uuid[], b.component_sku_id)], b.component_sku_id), b.qty, 1, now(), b.expire_at from sku_boms b join unnest($2::uuid[], $3::uuid[]) m(old_id,new_id) on b.bundle_sku_id=m.old_id where b.tenant_id=$1")
        .bind(tenant).bind(&source_skus).bind(&new_skus).execute(&mut **tx).await?;
    *copied_skus = Some(serde_json::to_value(
        source_skus.into_iter().zip(new_skus).collect::<Vec<_>>(),
    )?);
    Ok(applied(row))
}

